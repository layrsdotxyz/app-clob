/// poseidon2_permutation([s[0] + d, s[1] + e, s[2], s[3]])[0]
/// ```
pub fn hash_5(a: &[u8; 32], b: &[u8; 32], c: &[u8; 32], d: &[u8; 32], e: &[u8; 32]) -> ClobResult<[u8; 32]> {
    let iv = Fr::from(IV5);
    let s = poseidon2_permutation([
        Fr::from_be_bytes_mod_order(a),
        Fr::from_be_bytes_mod_order(b),
        Fr::from_be_bytes_mod_order(c),
        iv,
    ]);
    let d_fr = Fr::from_be_bytes_mod_order(d);
    let e_fr = Fr::from_be_bytes_mod_order(e);
    let out = poseidon2_permutation([s[0] + d_fr, s[1] + e_fr, s[2], s[3]]);
    Ok(fr_to_bytes32(out[0]))
}

/// Compute the Poseidon2 nullifier `H2(ownerKeyHash, noteNonce)`.
pub fn compute_nullifier(owner_key_hash: &[u8; 32], note_nonce: &[u8; 32]) -> ClobResult<[u8; 32]> {
    hash_2(owner_key_hash, note_nonce)
}

// ── Internal permutation ──────────────────────────────────────────────────────

/// Poseidon2 permutation over BN254 scalar field with state width 4.
///
/// This is the AUTH-CRITICAL function: produces the same output as
/// barretenberg's `crypto::poseidon2::poseidon2_permutation<BN254Params, 4>`.
///
/// # ⚠ Note on round constants
/// The placeholder constants in `ROUND_CONSTANTS` above are structurally correct
/// but have not been verified against the barretenberg reference implementation.
/// Before relying on this function for production note commitment computation,
/// run the cross-check test suite with known barretenberg output vectors.
fn poseidon2_permutation(mut state: [Fr; 4]) -> [Fr; 4] {
    let rc = parse_round_constants();

    // ── Full rounds (first R_F/2 = 4) ────────────────────────────────────────
    for round in 0..(RF / 2) {
        state = add_round_constants(state, &rc[round]);
        state = full_sbox(state);
        state = apply_mds(state);
    }

    // ── Partial rounds ────────────────────────────────────────────────────────
    for round in (RF / 2)..(RF / 2 + RP) {
        state[0] += rc[round][0];
        state[0] = sbox(state[0]);
        state = apply_mds(state);
    }

    // ── Full rounds (last R_F/2 = 4) ─────────────────────────────────────────
    for round in (RF / 2 + RP)..(RF + RP) {
        state = add_round_constants(state, &rc[round]);
        state = full_sbox(state);
        state = apply_mds(state);
    }

    state
}

fn add_round_constants(mut state: [Fr; 4], rc: &[Fr; 4]) -> [Fr; 4] {
    for (s, c) in state.iter_mut().zip(rc.iter()) {
        *s += c;
    }
    state
}

fn full_sbox(mut state: [Fr; 4]) -> [Fr; 4] {
    for s in state.iter_mut() {
        *s = sbox(*s);
    }
    state
}

/// S-box: x → x^5 mod p (α = 5 for BN254)
fn sbox(x: Fr) -> Fr {
    let x2 = x * x;
    let x4 = x2 * x2;
    x4 * x
}

/// MDS matrix multiplication over BN254 scalar field.
///
/// Uses a Cauchy-style MDS matrix for efficiency. The exact MDS values in
/// `MDS` are placeholders — replace with the barretenberg M_I matrix values.
fn apply_mds(state: [Fr; 4]) -> [Fr; 4] {
    let mut out = [Fr::ZERO; 4];
    for (i, o) in out.iter_mut().enumerate() {
        for (j, s) in state.iter().enumerate() {
            *o += Fr::from(MDS[i][j]) * s;
        }
    }
    out
}

fn parse_round_constants() -> Vec<[Fr; 4]> {
    ROUND_CONSTANTS
        .iter()
        .map(|row| {
            [
                parse_hex_fr(row[0]),
                parse_hex_fr(row[1]),
                parse_hex_fr(row[2]),
                parse_hex_fr(row[3]),
            ]
        })
        .collect()
}

fn parse_hex_fr(s: &str) -> Fr {
    let hex = s.strip_prefix("0x").unwrap_or(s);
    Fr::from_be_bytes_mod_order(&hex::decode(hex).unwrap_or_default())
}

fn fr_to_bytes32(f: Fr) -> [u8; 32] {
    let bytes = f.into_bigint().to_bytes_be();
    let mut out = [0u8; 32];
    let start = 32usize.saturating_sub(bytes.len());
    out[start..].copy_from_slice(&bytes[bytes.len().saturating_sub(32)..]);
    out
}

// ── Tests ─────────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    fn bytes32(n: u64) -> [u8; 32] {
        let mut b = [0u8; 32];
        b[24..32].copy_from_slice(&n.to_be_bytes());
        b
    }

    #[test]
    fn hash_2_is_deterministic() {
        let a = bytes32(1);
        let b = bytes32(2);
        assert_eq!(hash_2(&a, &b).unwrap(), hash_2(&a, &b).unwrap());
    }

    #[test]
    fn hash_2_differs_from_hash_3() {
        let a = bytes32(1);
        let b = bytes32(2);
        let c = bytes32(0);
        // hash_2(a, b) ≠ hash_3(a, b, 0) because IVs differ
        assert_ne!(hash_2(&a, &b).unwrap(), hash_3(&a, &b, &c).unwrap());
    }

    #[test]
    fn hash_4_input_order_matters() {
        let a = bytes32(1);
        let b = bytes32(2);
        let c = bytes32(3);
        let d = bytes32(4);
        assert_ne!(
            hash_4(&a, &b, &c, &d).unwrap(),
            hash_4(&d, &c, &b, &a).unwrap()
        );
    }

    #[test]
    fn compute_nullifier_matches_hash_2() {
        let key = bytes32(42);
        let nonce = bytes32(7);
        assert_eq!(
            compute_nullifier(&key, &nonce).unwrap(),
            hash_2(&key, &nonce).unwrap()
        );
    }

    #[test]
    fn hash_2_nonzero_output() {
        let a = bytes32(0);
        let b = bytes32(0);
        // Even with all-zero inputs the IV ensures non-zero output
        assert_ne!(hash_2(&a, &b).unwrap(), [0u8; 32]);
    }
}
