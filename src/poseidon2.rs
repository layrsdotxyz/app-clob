/// Compute `hash_4(a, b, c, d)` matching the Noir circuit's two-pass construction:
/// ```text
/// let s = poseidon2_permutation([a, b, c, iv4]);
/// poseidon2_permutation([s[0] + d, s[1], s[2], s[3]])[0]
/// ```
pub fn hash_4(a: &[u8; 32], b: &[u8; 32], c: &[u8; 32], d: &[u8; 32]) -> ClobResult<[u8; 32]> {
    let iv = Fr::from(IV4);
    let s = poseidon2_permutation([
        Fr::from_be_bytes_mod_order(a),
        Fr::from_be_bytes_mod_order(b),
        Fr::from_be_bytes_mod_order(c),
        iv,
    ]);
    let d_fr = Fr::from_be_bytes_mod_order(d);
    let out = poseidon2_permutation([s[0] + d_fr, s[1], s[2], s[3]]);
    Ok(fr_to_bytes32(out[0]))
}

